export function orchestratorSamplePayload(phase = "executor", width = SAMPLE_PAYLOAD.terminal_width) {
  const isExec = String(phase).toLowerCase() === "executor";
  const orchScenario = PREVIEW_SCENARIOS.find((s) => s.name === "orchestrator");
  const cloned = clonePayload(orchScenario?.payload ?? SAMPLE_PAYLOAD, width);
  cloned.model = { id: "orchestrator-neon", display_name: "Orchestrator (Neon)" };
  cloned.orchestrator = {
    phase: isExec ? "executor" : "planner",
    activeModel: isExec ? "Gemini 4 Hydrogen (XHigh)" : "Gemini 4 Neon (XHigh)",
    activeId: isExec ? "gemini-4-hydrogen" : "gemini-4-neon",
    plannerModel: "Gemini 4 Neon (XHigh)",
    executorModel: "Gemini 4 Hydrogen (XHigh)",
  };
  return cloned;
}

export function scenarioPayload(scenario, width = SAMPLE_PAYLOAD.terminal_width) {
  const source = scenario?.payload ?? SAMPLE_PAYLOAD;
  return {
    payload: clonePayload(source, width),
    git: scenario?.git ? { ...scenario.git } : null,
  };
}

function clonePayload(source, width) {
  return {
    ...source,
    terminal_width: width,
    model: source.model ? { ...source.model } : undefined,
    orchestrator: source.orchestrator ? { ...source.orchestrator } : undefined,
    workspace: source.workspace ? { ...source.workspace } : undefined,
    context_window: source.context_window
      ? {
        ...source.context_window,
        current_usage: source.context_window.current_usage
          ? { ...source.context_window.current_usage }
          : undefined,
      }
      : undefined,
    prompt_cache: source.prompt_cache ? { ...source.prompt_cache } : undefined,
    quota: Array.isArray(source.quota) ? source.quota.map((q) => ({ ...q })) : source.quota,
    cost: source.cost ? { ...source.cost } : undefined,
    cost_today: source.cost_today ? { ...source.cost_today } : undefined,
    tps: source.tps ? { ...source.tps } : undefined,
    subagents: Array.isArray(source.subagents)
      ? source.subagents.map((entry) => ({
        ...entry,
        context_window: entry.context_window
          ? { ...entry.context_window, current_usage: entry.context_window.current_usage ? { ...entry.context_window.current_usage } : undefined }
          : undefined,
      }))
      : [],
  };
}
